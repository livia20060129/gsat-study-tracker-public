"""Build browser lookup tables from the preserved official/ECDICT reference modules."""
import json
import re
from pathlib import Path

PARTS = ['noun', 'verb', 'adjective', 'adverb', 'preposition', 'conjunction', 'pronoun', 'article', 'auxiliary', 'interjection', 'unclassified']
BASE64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'


def read_table(path):
    source = path.read_text(encoding='utf-8')
    table = re.search(r'=\s*({.*})\s*;\s*$', source, re.S).group(1)
    return json.loads(re.sub(r',\s*}$', '}', table))


def write_compact_tables(output, vocabulary, translations):
    words = sorted(vocabulary)
    levels = ''.join(BASE64[sum(1 << (level - 1) for level in vocabulary[word]['levels'])] for word in words)
    parts = '|'.join(''.join(BASE64[PARTS.index(part)] for part in vocabulary[word]['parts']) for word in words)
    header = '// Generated by scripts/build_compact_vocabulary.py; see VOCABULARY_SOURCES.md.\n'
    values = {'CEEC_WORD_INDEX': '\n'.join(words), 'CEEC_LEVEL_MASKS': levels, 'CEEC_PART_CODES': parts}
    (output / 'ceecCompactIndex.ts').write_text(header + ''.join(
        f'export const {key} = {json.dumps(value, ensure_ascii=False)};\n' for key, value in values.items()), encoding='utf-8')
    rows = [json.dumps([[PARTS.index(part), meanings] for part, meanings in translations.get(word, {}).items()],
                       ensure_ascii=False, separators=(',', ':')) for word in words]
    (output / 'ceecCompactTranslations.ts').write_text(header + 'export const CEEC_MEANING_ROWS = '
        + json.dumps('\n'.join(rows), ensure_ascii=False) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    output = Path(__file__).resolve().parents[1] / 'src' / 'data'
    write_compact_tables(output, read_table(output / 'ceecVocabulary.ts'), read_table(output / 'ceecTranslations.ts'))
