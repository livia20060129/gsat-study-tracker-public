"""Keep explicit ECDICT POS labels for spellings with no usable Chinese translation."""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re
import unicodedata
from build_ecdict_lookup import MARKER, TAGS, groups


class OriginalText:
    def convert(self, value):
        return value


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--dictionary', type=Path, required=True)
    parser.add_argument('--project', type=Path, required=True)
    args = parser.parse_args()
    entries = {}
    with args.dictionary.open(encoding='utf-8-sig', newline='') as stream:
        for row in csv.DictReader(stream):
            word = unicodedata.normalize('NFKC', row['word']).strip().lower().replace('’', "'")
            if len(word) > 80 or not re.fullmatch(r"[a-z]+(?:['-][a-z]+)*", word):
                continue
            if groups(row['translation'], OriginalText()):
                continue
            parts = []
            for text in [row['translation'], row['definition']]:
                for line in text.split(r'\n'):
                    match = MARKER.match(line)
                    field = TAGS.get(match[1]) if match else None
                    if field and field not in parts:
                        parts.append(field)
            if parts:
                entries[word] = list(dict.fromkeys(entries.get(word, []) + parts))
    output = args.project / 'src/data/ecdictFallbackParts.ts'
    checksum = hashlib.sha256(args.dictionary.read_bytes()).hexdigest()
    output.write_text('// Generated by scripts/build_ecdict_fallback_parts.py.\n'
        '// Source: https://github.com/skywind3000/ECDICT (MIT; public/licenses/ECDICT-MIT.txt).\n'
        f'// Source SHA-256: {checksum}\n'
        "import type { EnglishReviewPartOfSpeech } from '../types.ts';\n\n"
        'export const ECDICT_FALLBACK_PARTS: Record<string, EnglishReviewPartOfSpeech[]> = '
        + json.dumps(dict(sorted(entries.items())), ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(json.dumps({'entries': len(entries), 'bytes': output.stat().st_size, 'sha256': checksum}))


if __name__ == '__main__':
    main()
